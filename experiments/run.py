"""Run every arranger over the corpus and write RESULTS.md.

    python experiments/run.py            # scores only
    python experiments/run.py --songs    # also keep the converted songs in experiments/out/

The table is the project's memory: change an arranger, run this, and the diff
of RESULTS.md shows exactly what the change bought and what it cost.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from eigenchip import __version__, metrics                      # noqa: E402
from eigenchip.arrangers import ARRANGERS, arrange              # noqa: E402
from eigenchip.ir import quantize                               # noqa: E402
from eigenchip.readers import read                              # noqa: E402
from eigenchip.writers import clio                              # noqa: E402

COLS = metrics.COLUMNS
HEAD = {"melody_recall": "melody", "bass_recall": "bass", "pitch_recall": "kept", "pitch_precision": "true",
        "chroma": "harmony", "onset_f1": "rhythm", "compression": "patterns"}


def cell(v):
    return "-" if v is None else "%.2f" % v


def run(keep_songs=False):
    corpus = os.path.join(ROOT, "corpus")
    with open(os.path.join(corpus, "manifest.json"), encoding="utf-8") as f:
        manifest = json.load(f)
    rows, problems = [], []
    out_dir = os.path.join(ROOT, "experiments", "out")
    for entry in manifest:
        grid = quantize(read(os.path.join(corpus, entry["file"])))
        for name in ARRANGERS:
            arr = arrange(grid, name)
            song = clio.to_song(arr, grid)
            problems += ["%s/%s: %s" % (entry["file"], name, p) for p in clio.validate(song)]
            rows.append((entry, name, metrics.evaluate(grid, arr, song, entry.get("truth")), grid))
            if keep_songs:
                os.makedirs(out_dir, exist_ok=True)
                path = os.path.join(out_dir, "%s.%s.json" % (entry["file"][:-4], name))
                with open(path, "w", encoding="utf-8") as f:
                    f.write(clio.dumps(song))
    return manifest, rows, problems


def report(manifest, rows):
    lines = ["# Results", "",
             "Generated by `python experiments/run.py` with eigenchip %s. Do not edit by hand." % __version__, "",
             "Scores run from 0 to 1 and compare notes, not sound: see `eigenchip/metrics.py`.", "",
             "| column | question it answers |", "| --- | --- |",
             "| melody | Does the lead voice play the real melody? |",
             "| bass | Does the bass voice play the real bass? |",
             "| kept | How much of what sounded in the original still sounds? |",
             "| true | How much of what sounds now was in the original? |",
             "| harmony | Is the pitch-class content of each beat the same? |",
             "| rhythm | Do notes start where they started? |",
             "| patterns | Unique patterns / patterns (lower = more repetition found) |", "",
             "## Average over the corpus", "",
             "| arranger | " + " | ".join(HEAD[c] for c in COLS) + " |",
             "| --- |" + " ---: |" * len(COLS)]
    for name in ARRANGERS:
        mine = [r[2] for r in rows if r[1] == name]
        cells = []
        for c in COLS:
            vals = [m[c] for m in mine if m[c] is not None]
            cells.append(cell(sum(vals) / len(vals)) if vals else "-")
        lines.append("| %s | %s |" % (name, " | ".join(cells)))
    lines += ["", "## Piece by piece", ""]
    for entry in manifest:
        mine = [r for r in rows if r[0] is entry]
        grid = mine[0][3]
        mean_poly, max_poly = metrics.polyphony(grid)
        lines += ["### %s" % entry["title"], "",
                  "%s %s" % (entry["source"], entry["stresses"]), "",
                  "`%s`, %s, up to %d notes at once, quantisation error %.2f steps." % (
                      entry["file"], entry["meter"], max_poly, grid.error), "",
                  "| arranger | " + " | ".join(HEAD[c] for c in COLS) + " |",
                  "| --- |" + " ---: |" * len(COLS)]
        for _e, name, res, _g in mine:
            lines.append("| %s | %s |" % (name, " | ".join(cell(res[c]) for c in COLS)))
        lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    manifest, rows, problems = run(keep_songs="--songs" in sys.argv)
    for p in problems:
        print("INVALID SONG:", p)
    with open(os.path.join(ROOT, "RESULTS.md"), "w", encoding="utf-8") as f:
        f.write(report(manifest, rows))
    print("wrote RESULTS.md (%d pieces x %d arrangers)%s" % (
        len(manifest), len(ARRANGERS), "" if not problems else " - %d invalid songs" % len(problems)))
    sys.exit(1 if problems else 0)
